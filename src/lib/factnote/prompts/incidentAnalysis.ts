/**
 * 出来事分析のシステム/ユーザープロンプト。
 *
 * v3 で判定の考え方を作り直した（docs/factnote/HANDOFF.md「判定ロジック v3」）:
 * - 「中立 = 真ん中」ではなく「公正 = 両者に同じ物差しを当てる」。結果が片寄るなら片寄ったまま書く
 * - 件数ではなく重さで判断する（重さの物差しを自分側・相手側に共通で定義）
 * - 原因（発端）と反応を分けて評価する
 * - 記録者が当事者の一方であることによる偏りを、根拠の種類（basis）と判定の確かさで扱う
 * - 立場を入れ替えても同じ判定になるかを確認させる
 * - 判定（verdict）を明示し、見解・結論はそこから導く（出力順もそうなるよう responseSchema 側で固定）
 *
 * v4: 改善点・問題点のそれぞれに「代わりにどうするとよいか（suggestion）」を付け、
 * 相手側についても「直した方がいいこと」を具体的な行動・言い方で示す。
 */

export const INCIDENT_ANALYSIS_PROMPT_VERSION = 'v4';

/** プロフィール（自分の立場・家族構成）のセクション。未登録なら空配列。 */
function peopleContextSection(peopleContext?: string): string[] {
  if (!peopleContext?.trim()) return [];
  return [
    '',
    '# 記録者と登場人物についての補足情報（本人が登録したプロフィール）',
    '以下は記録を書いている本人が登録した情報です。記録の中で誰が「自分（記録者）」で、',
    '誰が「相手」かを判断する手がかりにしてください。記録が相手の視点で書かれている・',
    '録音の話者ラベルが入れ替わっている可能性がある場合も、内容とこの情報から補正してください。',
    'どちらが記録者か判断できない場合は、自分側/相手側を断定せず unknowns に含め、verdict.leaning は undeterminable にしてください。',
    'ここに書かれていない人物を作り出したり、書かれた関係性と矛盾する記述をしたりしないでください。',
    '----- 補足情報ここから -----',
    peopleContext.trim(),
    '----- 補足情報ここまで -----',
  ];
}

